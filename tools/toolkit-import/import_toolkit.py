def _fold(label: str) -> str:
    """Lower-case and strip diacritics.

    The workbook mixes plain and accented transliterations in the same column
    ("Mrigashirsha" / "Mrigash\u012brsha", "Maghā", "Pūrva Phalgunī"). Folding
    first means one alias covers both, instead of the accented spellings being
    silently dropped.
    """
    decomposed = unicodedata.normalize("NFKD", label.lower())
    return "".join(c for c in decomposed if not unicodedata.combining(c))


def _clean_label(label: str) -> str:
    return " ".join(re.sub(r"[^a-z\s]+", " ", _fold(label)).split())


def resolve_nakshatra(label: str) -> str:
    """Map any spelling used in the workbook to a ``Nakshatra`` constant.

    The quarter notation is stripped first, since it travels in the same cell as
    the star name ("Uttara Phalguni 2-3-4Q", "Karthikai 2, 3 and 4th Quarters").
    """
    cleaned = _fold(label)
    # Drop quarter/pada notation: digits, ordinal suffixes, roman numerals and
    # the words that introduce them.
    cleaned = re.sub(r"[0-9]+\s*(?:st|nd|rd|th)?", " ", cleaned)
    cleaned = re.sub(
        r"\b(q|quarters?|padas?|half|first|second|third|fourth|and|i|ii|iii|iv)\b", " ", cleaned
    )
    cleaned = " ".join(re.sub(r"[^a-z\s]+", " ", cleaned).split())
    if cleaned in NAKSHATRA_ALIASES:
        return NAKSHATRA_ALIASES[cleaned]
    collapsed = cleaned.replace(" ", "")
    for alias, value in NAKSHATRA_ALIASES.items():
        if alias.replace(" ", "") == collapsed:
            return value
    raise ValueError(f"unknown nakshatra label: {label!r}")


def resolve_graha(label: str) -> str:
    """Map any planet spelling used in the workbook to a ``Graha`` constant.

    A label naming more than one planet is rejected as ambiguous rather than
    resolved to the first: PlanetsCharacteristics opens its node section with a
    combined "Rahu Ketu" row, and taking that as Rahu would shadow the real
    Rahu row two lines below.
    """
    cleaned = _clean_label(label)
    if cleaned in GRAHA_ALIASES:
        return GRAHA_ALIASES[cleaned]
    found = {GRAHA_ALIASES[t] for t in cleaned.split() if t in GRAHA_ALIASES}
    if len(found) == 1:
        return next(iter(found))
    if len(found) > 1:
        raise ValueError(f"ambiguous planet label names {sorted(found)}: {label!r}")
    raise ValueError(f"unknown planet label: {label!r}")


def resolve_sign(label: str) -> str:
    """Map any sign spelling used in the workbook to a ``Sign`` constant."""
    cleaned = _clean_label(label)
    if cleaned in SIGN_ALIASES:
        return SIGN_ALIASES[cleaned]
    for token in cleaned.split():
        if token in SIGN_ALIASES:
            return SIGN_ALIASES[token]
    raise ValueError(f"unknown sign label: {label!r}")


def parse_quarters(label: str) -> list[int]:
    """The quarters (padas) a star-sheet label covers, as sorted 1..4.

    The two star sheets each use their own notation, and both appear verbatim in
    one column:

    ``1Q`` ``2-3-4Q`` ``1-2Q`` ``4Q`` ``First Half`` ``Second Half``
    ``1st Quarter`` ``2, 3 and 4th Quarters`` ``1, 2, 3 quarter``
    ``2nd, 3rd and 4th Padas`` ``I-Quarter`` ``IV quarter``

    An empty result means the row covers the whole star (all four quarters).

    Note the digits are matched without requiring a trailing word boundary:
    in ``2-3-4Q`` the final 4 is butted against the Q, and a ``\b`` there
    dropped it - which silently made ``1Q`` and ``2-3-4Q`` overlap.
    """
    lowered = _fold(label)
    if re.search(r"\b(first|1st)\s+half\b", lowered):
        return [1, 2]
    if re.search(r"\b(second|2nd)\s+half\b", lowered):
        return [3, 4]

    quarters = set()
    # Bare or ordinal digits 1-4 that are not part of a longer number.
    for match in re.finditer(r"(?<![0-9])([1-4])(?![0-9])", lowered):
        quarters.add(int(match.group(1)))
    # Roman numerals, but only where they qualify a quarter/pada.
    for roman, value in _ROMAN_QUARTERS.items():
        if re.search(rf"\b{roman}\b[\s-]*(?:q\b|quarter|pada)", lowered):
            quarters.add(value)
    # Spelled-out numbers.
    for word, value in {"one": 1, "two": 2, "three": 3, "four": 4}.items():
        if re.search(rf"\b{word}\b", lowered):
            quarters.add(value)
    return sorted(quarters)


