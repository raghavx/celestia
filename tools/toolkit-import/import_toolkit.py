def run(workbook_path: Path, out: Path) -> str:
    sheets = read_workbook(workbook_path)
    titles = list(sheets)
    check_manifest(titles)

    version = detect_version(sheets[manifest.title_of(manifest.VERSION_SHEET_ID)])

    # T002 - the base resources every other task is layered on.
    write_sheets(out, sheets)
    write_manifest(out, titles)

    # T015 / T016 - the promise rule book.
    rules = extract_rules(sheets)
    write_tsv(out / "rules" / "promise-rules.tsv", RULES_HEADER, rules)

    # T026 - horary.
    write_tsv(out / "tables" / "horary-249.tsv", HORARY_HEADER, extract_horary(sheets))

    # T031 - the two star look-ups.
    write_tsv(
        out / "tables" / "star-professions.tsv",
        ["nakshatra", "quarters", "label", "professions", "classicalProfessions"],
        extract_star_table(sheets, manifest.STAR_PROFESSIONS_ID),
    )
    write_tsv(
        out / "tables" / "star-diseases.tsv",
        ["nakshatra", "quarters", "label", "bodyParts", "diseases"],
        extract_star_table(sheets, manifest.STAR_DISEASES_ID),
    )

    # T032 - the remaining typed tables.
    write_tsv(
        out / "tables" / "planet-house-signification.tsv",
        ["graha", "house", "text"],
        extract_planet_house_table(sheets, manifest.PLANET_SIGNIFICATION_ID),
    )
    write_tsv(
        out / "tables" / "higher-education-streams.tsv",
        ["graha", "house", "text"],
        extract_planet_house_table(sheets, manifest.EDUCATION_STREAMS_ID),
    )
    write_tsv(
        out / "tables" / "planet-friendship.tsv",
        ["of", "towards", "relation"],
        extract_friendship(sheets),
    )
    write_tsv(
        out / "tables" / "house-meanings.tsv",
        ["house", "text"],
        extract_indexed_text(sheets, manifest.HOUSE_MEANINGS_ID, 12),
    )
    write_tsv(
        out / "tables" / "relationship-rotation.tsv",
        ["cusp", "text"],
        extract_indexed_text(sheets, manifest.RELATIONSHIP_ID, 12),
    )

    grahas = [
        "SUN", "MOON", "MARS", "MERCURY", "JUPITER", "VENUS", "SATURN", "RAHU", "KETU",
    ]
    signs = [
        "ARIES", "TAURUS", "GEMINI", "CANCER", "LEO", "VIRGO", "LIBRA", "SCORPIO",
        "SAGITTARIUS", "CAPRICORN", "AQUARIUS", "PISCES",
    ]
    write_tsv(
        out / "tables" / "planet-characteristics.tsv",
        ["graha", "text"],
        extract_keyed_text(sheets, manifest.PLANET_CHARACTERISTICS_ID, resolve_graha, grahas),
    )
    write_tsv(
        out / "tables" / "planet-direction.tsv",
        ["graha", "text"],
        extract_keyed_text(sheets, manifest.PLANET_DIRECTION_ID, resolve_graha, grahas),
    )
    write_tsv(
        out / "tables" / "zodiac-characteristics.tsv",
        ["sign", "text"],
        extract_keyed_text(sheets, manifest.ZODIAC_CHARACTERISTICS_ID, resolve_sign, signs),
    )

    # Written last: the rule count is only known once the rules are parsed.
    write_properties(out, version, len(titles), len(rules), sha256_of(workbook_path))

    return f"toolkit {version}: {len(titles)} sheets, {len(rules)} rules -> {out}"


def main(argv: list[str]) -> int:
    if len(argv) < 2:
        print(
            "usage: import_toolkit.py <workbook.xlsx> [out_dir]\n"
            f"       out_dir defaults to {DEFAULT_OUT}",
            file=sys.stderr,
        )
        return 2
    workbook_path = Path(argv[1])
    if not workbook_path.is_file():
        print(f"no such workbook: {workbook_path}", file=sys.stderr)
        return 1
    out = Path(argv[2]) if len(argv) > 2 else DEFAULT_OUT
    try:
        print(run(workbook_path, out))
    except ImportError_ as exc:
        print(str(exc), file=sys.stderr)
        return 1
    except ValueError as exc:  # unknown alias labels surface here
        print(str(exc), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
