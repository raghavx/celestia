def _is_header_row(row: list[str], layout) -> bool:
    """True for a sheet's own column-heading row.

    Detected rather than hard-coded by index because the rule sheets disagree
    about whether they have one at all (Difficulty does not).
    """
    joined = " ".join(row).lower()
    headings = (
        "house sub lord", "connecting houses", "promise of event", "primary house",
        "supporting house", "supporting", "category", "matter", "event", "mater",
    )
    return any(h in joined for h in headings) and not any(c.isdigit() for c in joined[:3])


def extract_rules(sheets: dict[str, list[list[str]]]) -> list[list[str]]:
    """Every machine-readable house-formula rule, per research.md §2.

    Each sheet is read through the layout declared for it in ``manifest.py``;
    nothing is inferred from the shape of a row. A cell with no leading house
    number yields a rule with no houses: kept and retrievable, never matched
    automatically (FR-003, spec.md Edge Cases).
    """
    records: list[list[str]] = []
    for spec in manifest.RULE_SHEETS:
        rows = sheets.get(spec.title, [])
        layout = spec.rules
        for index, row in enumerate(rows, start=1):
            if index <= layout.skip_rows or not row:
                continue
            if _is_header_row(row, layout):
                continue
            records.extend(_rules_from_row(row, spec, index))
    return records


def _rules_from_row(row: list[str], spec: SheetSpec, row_number: int) -> list[list[str]]:
    """Zero or more rule records from one row of one rule sheet."""
    layout = spec.rules
    row_ref = f"r{row_number}"

    # Shape A: the whole sheet is formula lines. Property Astrology keeps two
    # columns of them, so every cell is tried.
    if layout.formula:
        out = []
        for column, cell in enumerate(row):
            parsed = parse_rule_formula(cell)
            if parsed is None:
                continue
            judged, houses, condition, matter = parsed
            if not matter:
                matter = cell.strip()
            ref = row_ref if column == 0 else f"{row_ref}c{column}"
            out.append(_rule_record(spec, spec.title, ref, matter, judged, houses, condition))
        return out

    # Shape B: the matter is in its own column and a formula cell sits beside it.
    if layout.formula_col is not None:
        matter = _cell(row, layout.matter_col or 0)
        parsed = parse_rule_formula(_cell(row, layout.formula_col))
        if not matter or parsed is None:
            return []
        judged, houses, condition, _ = parsed
        return [_rule_record(spec, spec.title, row_ref, matter, judged, houses, condition)]

    # Shape C: judged house, connecting houses and matter each in a known column.
    judged_text = _cell(row, layout.judged_col).strip()
    if not re.fullmatch(r"(1[0-2]|[1-9])", judged_text):
        return []
    judged = int(judged_text)
    matter = _cell(row, layout.matter_col) if layout.matter_col is not None else ""
    if not matter:
        return []
    houses, condition = ([], "")
    if layout.houses_col is not None:
        houses, condition = parse_rule_cell(_cell(row, layout.houses_col))
    category = _cell(row, layout.category_col) if layout.category_col is not None else spec.title
    return [_rule_record(spec, category or spec.title, row_ref, matter, judged, houses, condition)]


def _rule_record(
    spec: SheetSpec,
    category: str,
    row_ref: str,
    matter: str,
    judged: int,
    houses: list[int],
    condition: str,
) -> list[str]:
    sensitivity = classify_sensitivity(f"{matter} {condition}", spec.sensitivity)
    return [
        f"{spec.id}:{row_ref}",
        spec.id,
        category,
        matter,
        matter_key(matter),
        str(judged),
        ",".join(str(h) for h in houses),
        condition,
        sensitivity,
    ]


