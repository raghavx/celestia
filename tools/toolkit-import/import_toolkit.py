class ImportError_(RuntimeError):
    """A fatal, user-actionable import problem (printed, then non-zero exit)."""


def read_workbook(path: Path) -> dict[str, list[list[str]]]:
    """Every sheet's non-empty rows, keyed by the workbook's own sheet title."""
    workbook = load_workbook(filename=str(path), data_only=True)
    try:
        return {title: sheet_rows(workbook[title]) for title in workbook.sheetnames}
    finally:
        workbook.close()


def check_manifest(titles: list[str]) -> None:
    """Fail the import when the workbook and the manifest disagree (FR-013)."""
    found = set(titles)
    unmapped = sorted(found - manifest.TITLES)
    absent = sorted(manifest.TITLES - found)
    if unmapped or absent:
        raise ImportError_(
            f"manifest out of date: unmapped sheets {unmapped}, absent sheets {absent}"
        )


def detect_version(rows: list[list[str]]) -> str:
    """The toolkit release version: the latest date in the Version Control sheet."""
    dates: list[str] = []
    for row in rows:
        for cell in row:
            match = re.search(r"\b(\d{4})-(\d{2})-(\d{2})\b", cell)
            if match:
                dates.append(match.group(0))
    if not dates:
        raise ImportError_(
            "no date found in the Version Control sheet - cannot determine the "
            "toolkit version"
        )
    return max(dates)


def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


