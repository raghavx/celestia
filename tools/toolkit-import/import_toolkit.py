def normalise(value: object) -> str:
    """Render one workbook cell as text, verbatim apart from the documented fixes."""
    if value is None:
        return ""
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, datetime):
        return value.date().isoformat() if _is_midnight(value) else value.isoformat(sep=" ")
    if isinstance(value, date):
        return value.isoformat()
    if isinstance(value, float) and value.is_integer():
        text = str(int(value))
    elif isinstance(value, (int, float)):
        text = repr(value) if isinstance(value, float) else str(value)
    else:
        text = str(value)

    text = unicodedata.normalize("NFC", text).replace("\r\n", "\n").replace("\r", "\n")
    # Trim each line's trailing spaces; keep interior blank lines and leading indent.
    return "\n".join(line.rstrip() for line in text.split("\n")).strip()


def _is_midnight(value: datetime) -> bool:
    return (value.hour, value.minute, value.second, value.microsecond) == (0, 0, 0, 0)


def sheet_rows(worksheet) -> list[list[str]]:
    """Every non-empty row, in order, trailing empty cells trimmed.

    Merged ranges carry their value in the top-left cell only; the value is
    repeated across the range so a row reads the way it looks in the workbook.
    """
    merged: dict[tuple[int, int], object] = {}
    for rng in worksheet.merged_cells.ranges:
        anchor = worksheet.cell(row=rng.min_row, column=rng.min_col).value
        if anchor is None:
            continue
        for r in range(rng.min_row, rng.max_row + 1):
            for c in range(rng.min_col, rng.max_col + 1):
                merged[(r, c)] = anchor

    rows: list[list[str]] = []
    for row in worksheet.iter_rows():
        cells = [
            normalise(merged.get((cell.row, cell.column), cell.value)) for cell in row
        ]
        while cells and cells[-1] == "":
            cells.pop()
        if cells:
            rows.append(cells)
    return rows


