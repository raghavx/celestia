_HORARY_NUMBER = re.compile(r"^[lLiI|]?(\d{1,3})$")


def _horary_number(cell: str) -> int | None:
    """The row's horary number, correcting the single known source error.

    The 249Mindsets sheet mis-numbers row 107 as "L07" (research.md §10). That
    one substitution is the only fix-up applied anywhere in the import: the
    character is an ``L`` where a ``1`` belongs, so the same reading also
    repairs the visually identical ``I``/``|`` slips if they occur.
    """
    text = cell.strip()
    match = _HORARY_NUMBER.match(text)
    if not match:
        return None
    number = int(match.group(1)) if text[0].isdigit() else int("1" + match.group(1))
    return number if 1 <= number <= 249 else None


def extract_horary(sheets: dict[str, list[list[str]]]) -> list[list[str]]:
    """Merge the subdivision table and the mindset table into one keyed table.

    Subdivisions: No., Sign, Star, From, To, Sign Lord, Star Lord, Sub Lord.
    Mindsets:     Sub No., Rashi, From, To, Sign Lord, Star lord, Sub lord, Mindset.
    """
    subdivisions = _horary_rows(sheets, manifest.title_of(manifest.HORARY_SUBDIVISIONS_ID))
    mindsets = _horary_rows(sheets, manifest.title_of(manifest.HORARY_MINDSETS_ID))

    for label, table in (("subdivision", subdivisions), ("mindset", mindsets)):
        missing = [n for n in range(1, 250) if n not in table]
        if missing:
            raise ImportError_(
                f"249 {label} table incomplete: {len(missing)} numbers missing "
                f"(first few: {missing[:5]})"
            )

    records = []
    for number in range(1, 250):
        sub = subdivisions[number]
        mind = mindsets[number]
        records.append([
            str(number),
            _cell(sub, 1),          # sign
            _cell(sub, 2),          # star
            _cell(sub, 3),          # from
            _cell(sub, 4),          # to
            resolve_graha(_cell(sub, 5)),   # sign lord
            resolve_graha(_cell(sub, 6)),   # star lord
            resolve_graha(_cell(sub, 7)),   # sub lord
            _cell(mind, 7),         # mindset
        ])
    return records


HORARY_HEADER = [
    "number", "sign", "star", "fromDeg", "toDeg", "signLord", "starLord", "subLord", "mindset",
]


def _horary_rows(sheets: dict[str, list[list[str]]], title: str) -> dict[int, list[str]]:
    rows: dict[int, list[str]] = {}
    for row in sheets.get(title, []):
        if not row:
            continue
        number = _horary_number(row[0])
        if number is not None and number not in rows:
            rows[number] = row
    return rows


def _cell(row: list[str], index: int | None) -> str:
    if index is None or index >= len(row):
        return ""
    return row[index]


