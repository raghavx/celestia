def classify_sensitivity(text: str, sheet_default: str) -> str:
    """The sheet's default, raised (never lowered) by keywords in the rule itself.

    Known limitation (research.md §5): this fires on favourable wording too
    ("good immunity"), so a house with only good-health rules still carries the
    health advisory. Kept for v1 - a harmless advisory on good news - and the
    per-rule class is recorded so SPEC-011 can narrow it to adverse rules.
    """
    lowered = text.lower()
    found = sheet_default
    for words, cls in (
        (_FINANCE_WORDS, "FINANCE"),
        (_HEALTH_WORDS, "HEALTH"),
        (_LONGEVITY_WORDS, "LONGEVITY"),
    ):
        if any(w in lowered for w in words):
            if SENSITIVITY_ORDER[cls] > SENSITIVITY_ORDER[found]:
                found = cls
    return found


