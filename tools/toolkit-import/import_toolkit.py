def extract_star_table(sheets: dict[str, list[list[str]]], sheet_id: str) -> list[list[str]]:
    """A star sheet keyed by nakshatra + the quarters its row covers (§6)."""
    records = []
    for row in sheets.get(manifest.title_of(sheet_id), []):
        if not row or not row[0].strip():
            continue
        label = row[0].strip()
        try:
            nakshatra = resolve_nakshatra(label)
        except ValueError:
            continue  # header or note row
        quarters = parse_quarters(label)
        records.append([
            nakshatra,
            ",".join(str(q) for q in quarters) or "1,2,3,4",
            label,
            _cell(row, 1),
            _cell(row, 2),
        ])
    return records


def extract_planet_house_table(sheets: dict[str, list[list[str]]], sheet_id: str) -> list[list[str]]:
    """A long-format planet x house sheet: planet, house, text (one row each)."""
    records = []
    seen: set[tuple[str, int]] = set()
    for row in sheets.get(manifest.title_of(sheet_id), []):
        if not row or not row[0].strip():
            continue
        try:
            graha = resolve_graha(row[0])
        except ValueError:
            continue  # header or note row
        house_text = _cell(row, 1).strip()
        match = re.fullmatch(r"(1[0-2]|[1-9])(?:st|nd|rd|th)?", house_text)
        if not match:
            continue
        house = int(match.group(1))
        text = _cell(row, 2)
        if text and (graha, house) not in seen:
            seen.add((graha, house))
            records.append([graha, str(house), text])
    return records


def extract_friendship(sheets: dict[str, list[list[str]]]) -> list[list[str]]:
    """The 72 ordered planet pairs as FRIENDLY / NEUTRAL / ENEMY.

    The grid's header row is found by scanning for the first row where several
    cells resolve to grahas, because the sheet opens with a title row.
    """
    rows = sheets.get(manifest.title_of(manifest.FRIENDSHIP_ID), [])
    header_index, columns = -1, {}
    for index, row in enumerate(rows):
        found = {}
        for column, cell in enumerate(row):
            try:
                found[column] = resolve_graha(cell)
            except ValueError:
                continue
        if len(found) >= 5:
            header_index, columns = index, found
            break
    if header_index < 0:
        return []

    records = []
    for row in rows[header_index + 1 :]:
        of = None
        for cell in row:
            try:
                of = resolve_graha(cell)
                break
            except ValueError:
                continue
        if of is None:
            continue
        for column, towards in columns.items():
            if towards == of:
                continue
            text = _cell(row, column)
            if text:
                records.append([of, towards, _friendship_value(text)])
    return records


def _friendship_value(text: str) -> str:
    lowered = text.strip().lower()
    if "friend" in lowered:
        return "FRIENDLY"
    if "enem" in lowered:
        return "ENEMY"
    return "NEUTRAL"


def extract_indexed_text(
    sheets: dict[str, list[list[str]]], sheet_id: str, limit: int
) -> list[list[str]]:
    """A ``1..limit`` keyed sheet (house meanings, relationship by cusp)."""
    records = []
    seen: set[int] = set()
    for row in sheets.get(manifest.title_of(sheet_id), []):
        if not row:
            continue
        match = re.fullmatch(r"(\d{1,2})(?:st|nd|rd|th)?", row[0].strip())
        if not match:
            continue
        key = int(match.group(1))
        if not 1 <= key <= limit or key in seen:
            continue
        text = " ".join(c for c in row[1:] if c).strip()
        if text:
            seen.add(key)
            records.append([str(key), text])
    return sorted(records, key=lambda r: int(r[0]))


def extract_keyed_text(
    sheets: dict[str, list[list[str]]], sheet_id: str, resolver, expected: list[str]
) -> list[list[str]]:
    """A sheet keyed by a single planet or sign name (research.md §12).

    Rows whose label resolves ambiguously are skipped: PlanetsCharacteristics
    opens its node section with a combined "Rahu Ketu" row before the two
    specific ones, and taking that would shadow the real Rahu row.
    """
    title = manifest.title_of(sheet_id)
    records: list[list[str]] = []
    seen: set[str] = set()
    for row in sheets.get(title, []):
        if not row or not row[0].strip():
            continue
        try:
            key = resolver(row[0])
        except ValueError:
            continue  # header, note, or an ambiguous label
        if key in seen:
            continue
        text = " ".join(c for c in row[1:] if c).strip()
        if text:
            seen.add(key)
            records.append([key, text])
    absent = [k for k in expected if k not in seen]
    if absent:
        raise ImportError_(
            f"{title}: no row resolved to {absent} - add the spelling to the "
            f"alias table (research.md §12)"
        )
    return records


