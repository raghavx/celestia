def tsv_escape(text: str) -> str:
    r"""Escape a cell for TSV: ``\`` then tab and newline."""
    return (
        text.replace("\\", "\\\\").replace("\t", "\\t").replace("\r\n", "\\n").replace("\n", "\\n")
    )


def write_tsv(path: Path, header: list[str], records: list[list[str]]) -> None:
    """Write ``# banner`` + header + one record per line, LF-terminated, UTF-8."""
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [TOOL_BANNER, "\t".join(header)]
    lines.extend("\t".join(tsv_escape(c) for c in rec) for rec in records)
    write_text_lf(path, "\n".join(lines) + "\n")


def write_text_lf(path: Path, text: str) -> None:
    """Write UTF-8 with LF endings on every platform.

    Bytes rather than ``write_text(newline=...)``: the keyword needs Python 3.10
    and this tool runs on whatever the developer has. Writing the encoded text
    also guarantees no platform translates the line endings, which output
    determinism depends on (SC-006).
    """
    path.write_bytes(text.encode("utf-8"))


