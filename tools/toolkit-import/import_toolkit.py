_HOUSE_SEPARATOR = re.compile(r"^[\s,;&/]*(?:and\b)?[\s,;&/]*", re.IGNORECASE)
_HOUSE_TOKEN = re.compile(r"^(1[0-2]|[1-9])(?:st|nd|rd|th)?\b")
_FORMULA = re.compile(r"^\s*(1[0-2]|[1-9])\s*=\s*(.*)$", re.DOTALL)

#: A trailing clause opening with one of these is a condition, not the matter.
_CONDITION_OPENERS = (
    "+",
    "with ",
    "without ",
    "if ",
    "when ",
    "unless ",
    "provided ",
    "and not ",
    "but not ",
    "not related",
    "in ",
    "aspected ",
)


def parse_houses_prefix(text: str) -> tuple[list[int], str]:
    """Split a leading house list off ``text``.

    Only a run of 1..12 separated by commas / ``and`` / ``&`` / ``/`` counts.
    The first token that is not a house number ends the list; everything from
    there is returned untouched (FR-003: never invent houses).
    """
    houses: list[int] = []
    rest = text
    while True:
        trimmed = _HOUSE_SEPARATOR.sub("", rest, count=1)
        match = _HOUSE_TOKEN.match(trimmed)
        if not match:
            break
        # A house list must be separated from the next token; "12 housing loan"
        # keeps 12 but stops there, which is what we want.
        houses.append(int(match.group(1)))
        rest = trimmed[match.end() :]
        # Stop unless what follows is another separator + house number.
        probe = _HOUSE_SEPARATOR.sub("", rest, count=1)
        if not _HOUSE_TOKEN.match(probe) or probe == rest:
            break
    deduped: list[int] = []
    for h in houses:
        if h not in deduped:
            deduped.append(h)
    return deduped, rest.strip()


def parse_rule_cell(cell: str) -> tuple[list[int], str]:
    """A house-list cell from a rule *table*: houses + verbatim condition.

    ``"7"`` -> ([7], "");  ``"6, 8, 12 + Mars / Sun"`` -> ([6,8,12], "+ Mars / Sun");
    ``"Saturn as 7th sub lord"`` -> ([], the whole text) - never auto-matched.
    """
    text = cell.strip()
    if not text:
        return [], ""
    houses, rest = parse_houses_prefix(text)
    if not houses:
        return [], text
    return houses, rest


def parse_rule_formula(line: str) -> tuple[int | None, list[int], str, str] | None:
    """A formula line from a rule *sheet*: ``H = h1, h2 ... matter``.

    Returns ``(judgedHouse, houses, condition, matter)``, or ``None`` when the
    line is not a formula at all. A leading clause such as
    ``with influence of Jupiter,`` becomes the condition; the remainder is the
    matter, kept word for word.
    """
    match = _FORMULA.match(line)
    if not match:
        return None
    judged = int(match.group(1))
    houses, rest = parse_houses_prefix(match.group(2))
    condition = ""
    matter = rest
    lowered = rest.lower()
    if any(lowered.startswith(opener) for opener in _CONDITION_OPENERS):
        head, sep, tail = rest.partition(",")
        if sep and tail.strip():
            condition, matter = head.strip(), tail.strip()
        else:
            condition, matter = rest, ""
    return judged, houses, condition, matter


def matter_key(matter: str) -> str:
    """Lower-case, punctuation-stripped matter (research.md §8).

    Hits sharing a key are the same promise written in different sheets, so the
    answer stage can report them once instead of as independent confirmations.
    """
    collapsed = re.sub(r"[^a-z0-9\s]+", " ", matter.lower())
    return " ".join(collapsed.split())


