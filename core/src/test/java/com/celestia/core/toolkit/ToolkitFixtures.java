package com.celestia.core.toolkit;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

/**
 * Writes the synthetic toolkit roots the tests load (SPEC-010 T012/T022/T029/T035).
 *
 * <h2>Why fixtures, and why separate roots</h2>
 *
 * The licensed workbook is never committed, so the real resources only exist
 * after the owner runs the import (T047). Everything that does not need the
 * licensed <em>text</em> is tested against synthetic data instead, which keeps
 * {@code ./mvnw verify} green from the first commit.
 *
 * Each fixture lives at its own classpath root under
 * {@code com/celestia/core/toolkit/<name>/}, never at the production root:
 * {@code src/test/resources} shadows {@code src/main/resources} at the same
 * path, so a fixture there would permanently hide the real toolkit from
 * {@link KpToolkit#bundled()}.
 *
 * <h2>Generated in Java, on purpose</h2>
 *
 * The horary and star fixtures are generated by iterating the engine's own
 * enums and calling {@code Horary249}, not hand-authored and not produced by
 * the Python import tool. Those columns are the engine's calculation, not
 * licensed content, so generating them keeps one source of truth and means a
 * drift in the engine shows up as a test failure rather than a stale fixture.
 */
final class ToolkitFixtures {

    /** Where the fixture roots are written: {@code target/test-classes/...}. */
    static final Path TEST_CLASSES = Path.of("target", "test-classes");

    static final String BASE = "com/celestia/core/toolkit";

    private ToolkitFixtures() {}

    /** Resolve a fixture root's directory on disk. */
    static Path dir(String name) {
        return TEST_CLASSES.resolve(BASE).resolve(name);
    }

    /** The classpath root string to hand {@link KpToolkit#load(String)}. */
    static String root(String name) {
        return BASE + "/" + name;
    }

    /**
     * Write {@code toolkit.properties} and {@code manifest.tsv} for a root.
     *
     * <p>Every load validates these two against each other, so even a fixture
     * that only cares about one table needs a self-consistent pair.
     */
    static void writeRelease(String name, int sheetCount, int ruleCount) {
        Path target = dir(name);
        write(
                target.resolve("toolkit.properties"),
                """
                # test fixture
                title=Prediction ToolKit for Advanced (fixture)
                version=2026-09-12
                sheets=%d
                rules=%d
                sourceSha256=%s
                """
                        .formatted(sheetCount, ruleCount, "0".repeat(64)));
    }

    /** Write a TSV with the toolkit's escaping rules. */
    static void writeTsv(String name, String relativePath, List<String> header, List<List<String>> records) {
        StringBuilder out = new StringBuilder("# test fixture\n");
        out.append(String.join("\t", header)).append('\n');
        for (List<String> record : records) {
            out.append(record.stream().map(ToolkitFixtures::escape).collect(java.util.stream.Collectors.joining("\t")))
                    .append('\n');
        }
        write(dir(name).resolve(relativePath), out.toString());
    }

    private static String escape(String cell) {
        return cell.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n");
    }

    static void write(Path path, String content) {
        try {
            Files.createDirectories(path.getParent());
            Files.writeString(path, content, StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new UncheckedIOException("failed writing fixture " + path, e);
        }
    }
}
